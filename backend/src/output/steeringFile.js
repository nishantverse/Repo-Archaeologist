import fs from 'fs'
import path from 'path'

/**
 * Writes a Kiro steering file to <targetPath>/.kiro/steering/archaeology.md
 * containing the full analysis payload formatted as Markdown.
 *
 * @param {string} targetPath - Absolute path to the scanned repository root.
 * @param {object} payload    - Full AnalysisPayload from the pipeline.
 */
export async function writeSteeringFile(targetPath, payload) {
  try {
    // 8.2 — Compute output path
    const outputPath = path.join(targetPath, '.kiro', 'steering', 'archaeology.md')

    // 8.3 — Build Markdown content
    const content = buildMarkdown(payload)

    // 8.4 — Ensure directory exists
    await fs.promises.mkdir(path.dirname(outputPath), { recursive: true })

    // 8.5 — Write file
    await fs.promises.writeFile(outputPath, content, 'utf8')
  } catch (err) {
    // 8.6 — Non-fatal: warn and continue
    console.warn('Warning: could not write steering file:', err.message)
  }
}

/**
 * Builds the full Markdown string from the analysis payload.
 */
function buildMarkdown(payload) {
  const { techDebt, deps, flow, humanSummary, constraints } = payload
  const { megaFiles, todos } = techDebt
  const { dead } = deps

  const lines = []

  // YAML front matter
  lines.push('---')
  lines.push('inclusion: auto')
  lines.push('---')
  lines.push('')

  // Title
  lines.push('# Repository Architecture (Generated by Repo Archaeologist)')
  lines.push('')

  // Data Flow
  lines.push('## Data Flow')
  lines.push('')
  lines.push(flow.join(' → '))
  lines.push('')

  // Onboarding Summary
  lines.push('## Onboarding Summary')
  lines.push('')
  lines.push(humanSummary)
  lines.push('')

  // Tech Debt
  lines.push('## Tech Debt')
  lines.push('')

  lines.push('### Large Files (>500 lines)')
  lines.push('')
  if (megaFiles.length > 0) {
    for (const f of megaFiles) {
      lines.push(`- \`${f.path}\` — ${f.lines} lines`)
    }
  } else {
    lines.push('No oversized files detected.')
  }
  lines.push('')

  lines.push('### Outstanding TODOs')
  lines.push('')
  if (todos.length > 0) {
    for (const todo of todos) {
      lines.push(`- \`${todo.file}:${todo.line}\` — Added ~${todo.age}`)
    }
  } else {
    lines.push('No TODO comments found.')
  }
  lines.push('')

  // Dead Dependencies
  lines.push('## Dead Dependencies')
  lines.push('')
  if (dead.length > 0) {
    for (const dep of dead) {
      lines.push(`- ${dep}`)
    }
  } else {
    lines.push('None detected.')
  }
  lines.push('')

  // Architectural Constraints
  lines.push('## Architectural Constraints')
  lines.push('')
  constraints.forEach((constraint, i) => {
    lines.push(`${i + 1}. ${constraint}`)
  })
  lines.push('')

  // Footer
  lines.push('---')
  lines.push(`*Generated by repo-archaeologist on ${new Date().toISOString()}*`)

  return lines.join('\n')
}
